//! Maintenance tasks for cxvm, run with `cargo xtask <task>`.
//!
//! `catalog` regenerates the lists of installable releases embedded in cxvm:
//! `catalog/clang.toml` from LLVM's GitHub releases and `catalog/gcc.toml` from xPack's. See
//! `docs/backends.md` for the asset names and integrity data it relies on.

use std::collections::BTreeMap;
use std::fmt;
use std::io::{Read, Write};
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

const LLVM_RELEASES_API: &str = "https://api.github.com/repos/llvm/llvm-project/releases";
const XPACK_GCC_RELEASES_API: &str =
    "https://api.github.com/repos/xpack-dev-tools/gcc-xpack/releases";

/// Every release from this one on is in the catalog.
const ALL_FROM: V = V(19, 1, 0);
/// Below [`ALL_FROM`], the newest patch release of each major from this one on.
const OLDEST_MAJOR: u32 = 11;

const CLANG_HEADER: &str = "\
# Installable Clang releases, embedded in cxvm.
# Generated by `cargo xtask catalog` from LLVM's GitHub releases; do not edit by hand.
# `source` says where `sha256` comes from (see docs/backends.md).
";

const GCC_HEADER: &str = "\
# Installable GCC releases, embedded in cxvm.
# Generated by `cargo xtask catalog` from xPack GCC's GitHub releases; do not edit by hand.
# `source` says where `sha256` comes from (see docs/backends.md).
";

const USAGE: &str = "\
usage: cargo xtask catalog [clang|gcc] [--hash-missing] [--add <x.y.z>]...

Regenerates the catalogs embedded in cxvm; both without `clang` or `gcc`.

catalog/clang.toml, from LLVM's GitHub releases: every release from 19.1.0, the newest patch
of each major from 11 to 18, the versions passed with --add, and every version already in the
catalog. Known entries are kept, never re-hashed.

  --hash-missing   download and hash assets that have no upstream checksum
  --add <x.y.z>    also include this release

catalog/gcc.toml, from xPack GCC's GitHub releases: every GCC version, from its highest xPack
build, and every version already in the catalog.

GITHUB_TOKEN, if set, is sent to the GitHub API to raise its rate limit.";

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let result = match args.split_first() {
        Some((task, rest)) if task == "catalog" => parse_catalog_args(rest).and_then(|options| {
            let http = Http::new();
            if options.clang {
                clang_catalog(&http, &options)?;
            }
            if options.gcc {
                gcc_catalog(&http)?;
            }
            Ok(())
        }),
        _ => Err(USAGE.into()),
    };
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(err) => {
            eprintln!("error: {err}");
            ExitCode::FAILURE
        }
    }
}

type Result<T, E = String> = std::result::Result<T, E>;

#[derive(Debug, Default)]
struct Options {
    clang: bool,
    gcc: bool,
    hash_missing: bool,
    add: Vec<V>,
}

fn parse_catalog_args(args: &[String]) -> Result<Options> {
    let mut options = Options::default();
    let mut args = args.iter();
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "clang" => options.clang = true,
            "gcc" => options.gcc = true,
            "--hash-missing" => options.hash_missing = true,
            "--add" => {
                let value = args.next().ok_or("--add needs a version")?;
                options.add.push(value.parse()?);
            }
            other => return Err(format!("unknown argument `{other}`\n\n{USAGE}")),
        }
    }
    if !options.clang && !options.gcc {
        (options.clang, options.gcc) = (true, true);
    } else if !options.clang && (options.hash_missing || !options.add.is_empty()) {
        return Err(format!(
            "--hash-missing and --add apply to the clang catalog only\n\n{USAGE}"
        ));
    }
    Ok(options)
}

/// An exact release version.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
struct V(u32, u32, u32);

impl std::str::FromStr for V {
    type Err = String;

    fn from_str(s: &str) -> Result<Self> {
        let parts: Vec<u32> = s
            .split('.')
            .map(|part| part.parse().ok().filter(|_| !part.starts_with('+')))
            .collect::<Option<_>>()
            .ok_or_else(|| format!("`{s}` is not an x.y.z version"))?;
        match parts[..] {
            [major, minor, patch] => Ok(V(major, minor, patch)),
            _ => Err(format!("`{s}` is not an x.y.z version")),
        }
    }
}

impl fmt::Display for V {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}.{}.{}", self.0, self.1, self.2)
    }
}

/// A GitHub release, as returned by the releases API.
#[derive(Debug, Deserialize)]
struct Release {
    tag_name: String,
    draft: bool,
    prerelease: bool,
    assets: Vec<Asset>,
}

#[derive(Debug, Clone, Deserialize)]
struct Asset {
    name: String,
    size: u64,
    /// `sha256:<hex>`, computed by GitHub; only on assets uploaded since mid-2025.
    digest: Option<String>,
    browser_download_url: String,
}

/// A catalog file. Must stay in sync with `src/catalog.rs`.
#[derive(Debug, Default, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
struct Catalog {
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    clang: Vec<Entry>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    gcc: Vec<Entry>,
}

#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
struct Entry {
    version: String,
    asset: String,
    url: String,
    size: u64,
    sha256: String,
    source: Source,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "kebab-case")]
enum Source {
    /// The asset's `digest` in the GitHub API, cross-checked with the attestation if any.
    GithubDigest,
    /// The subject of the asset's SLSA provenance (`<asset>.jsonl`).
    Attestation,
    /// The checksum file published next to it: `<asset>.sha256`, or xPack's `<asset>.sha`.
    UpstreamSha256,
    /// Downloaded and hashed by this xtask.
    HashedAtGeneration,
}

/// `catalog/<file>` in the workspace.
fn catalog_path(file: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask lives in the workspace")
        .join("catalog")
        .join(file)
}

/// The catalog at `path`; empty if there is none yet.
fn read_catalog(path: &Path) -> Result<Catalog> {
    match std::fs::read_to_string(path) {
        Ok(text) => toml::from_str(&text).map_err(|e| format!("{}: {e}", path.display())),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Catalog::default()),
        Err(e) => Err(format!("cannot read {}: {e}", path.display())),
    }
}

fn by_version(entries: Vec<Entry>) -> Result<BTreeMap<V, Entry>> {
    entries
        .into_iter()
        .map(|entry| Ok((entry.version.parse()?, entry)))
        .collect()
}

fn write_catalog(path: &Path, header: &str, catalog: &Catalog) -> Result<()> {
    let body = toml::to_string(catalog).map_err(|e| e.to_string())?;
    std::fs::create_dir_all(path.parent().expect("has a parent")).map_err(|e| e.to_string())?;
    std::fs::write(path, format!("{header}\n{body}"))
        .map_err(|e| format!("cannot write {}: {e}", path.display()))?;
    eprintln!(
        "wrote {} ({} releases)",
        path.display(),
        catalog.clang.len() + catalog.gcc.len()
    );
    Ok(())
}

fn clang_catalog(http: &Http, options: &Options) -> Result<()> {
    let path = catalog_path("clang.toml");
    let mut entries = by_version(read_catalog(&path)?.clang)?;

    let releases = http.releases(LLVM_RELEASES_API)?;
    let picked: Vec<(V, &Release, &Asset)> = releases
        .iter()
        .filter(|r| !r.draft && !r.prerelease)
        .filter_map(|r| {
            let version = parse_tag(&r.tag_name)?;
            Some((version, r, pick_asset(version, &r.assets)?))
        })
        .collect();
    let wanted = wanted_versions(
        picked.iter().map(|(v, ..)| *v),
        &options.add,
        entries.keys().copied(),
    );
    for version in &options.add {
        if !picked.iter().any(|(v, ..)| v == version) {
            return Err(format!(
                "--add {version}: no such release with an x86_64 Linux asset"
            ));
        }
    }

    let mut skipped = Vec::new();
    for (version, release, asset) in picked.iter().filter(|(v, ..)| wanted.contains(v)) {
        let known = entries.get(version);
        if let Some(known) = known
            && known.asset != asset.name
        {
            return Err(format!(
                "{version}: the catalog has asset {} but the release now picks {}; \
                 remove the entry to regenerate it",
                known.asset, asset.name
            ));
        }
        let upstream = http.upstream_sha256(release, asset)?;
        let (sha256, source) = match (upstream, known) {
            (Some((sha256, source)), Some(known)) => {
                if sha256 != known.sha256 {
                    return Err(format!(
                        "{version}: upstream sha256 {sha256} differs from the catalog's {}",
                        known.sha256
                    ));
                }
                (sha256, source)
            }
            (Some(found), None) => found,
            (None, Some(known)) => (known.sha256.clone(), known.source),
            (None, None) if options.hash_missing => (http.hash(asset)?, Source::HashedAtGeneration),
            (None, None) => {
                skipped.push(*version);
                continue;
            }
        };
        let entry = Entry {
            version: version.to_string(),
            asset: asset.name.clone(),
            url: asset.browser_download_url.clone(),
            size: asset.size,
            sha256,
            source,
        };
        if known != Some(&entry) {
            eprintln!("{version}: {} ({:?})", entry.asset, entry.source);
        }
        entries.insert(*version, entry);
    }

    let catalog = Catalog {
        clang: entries.into_values().collect(),
        gcc: Vec::new(),
    };
    write_catalog(&path, CLANG_HEADER, &catalog)?;
    if !skipped.is_empty() {
        let list: Vec<String> = skipped.iter().map(V::to_string).collect();
        eprintln!(
            "skipped, no upstream checksum: {}\n  rerun with --hash-missing to download and hash them",
            list.join(", ")
        );
    }
    Ok(())
}

fn gcc_catalog(http: &Http) -> Result<()> {
    let path = catalog_path("gcc.toml");
    let mut entries = by_version(read_catalog(&path)?.gcc)?;

    let releases = http.releases(XPACK_GCC_RELEASES_API)?;
    for (version, (_, release, asset)) in pick_xpack_builds(&releases) {
        let sha256 = http.xpack_sha256(release, asset)?;
        let source = match &asset.digest {
            Some(_) => Source::GithubDigest,
            None => Source::UpstreamSha256,
        };
        let known = entries.get(&version);
        if let Some(known) = known
            && known.asset == asset.name
            && known.sha256 != sha256
        {
            return Err(format!(
                "{version}: upstream sha256 {sha256} differs from the catalog's {}",
                known.sha256
            ));
        }
        let entry = Entry {
            version: version.to_string(),
            asset: asset.name.clone(),
            url: asset.browser_download_url.clone(),
            size: asset.size,
            sha256,
            source,
        };
        if known != Some(&entry) {
            eprintln!("{version}: {} ({:?})", entry.asset, entry.source);
        }
        entries.insert(version, entry);
    }

    let catalog = Catalog {
        clang: Vec::new(),
        gcc: entries.into_values().collect(),
    };
    write_catalog(&path, GCC_HEADER, &catalog)
}

/// `v13.3.0-2` → GCC 13.3.0, xPack build 2; `None` for other tags.
fn parse_xpack_tag(tag: &str) -> Option<(V, u32)> {
    let (version, build) = tag.strip_prefix('v')?.split_once('-')?;
    let build = build.parse().ok().filter(|_| !build.starts_with('+'))?;
    Some((version.parse().ok()?, build))
}

/// The x86_64 Linux archive of each GCC version, from its highest xPack build that has one.
fn pick_xpack_builds(releases: &[Release]) -> BTreeMap<V, (u32, &Release, &Asset)> {
    let mut picked: BTreeMap<V, (u32, &Release, &Asset)> = BTreeMap::new();
    for release in releases.iter().filter(|r| !r.draft && !r.prerelease) {
        let Some((version, build)) = parse_xpack_tag(&release.tag_name) else {
            continue;
        };
        let name = format!("xpack-gcc-{version}-{build}-linux-x64.tar.gz");
        let Some(asset) = release.assets.iter().find(|a| a.name == name) else {
            continue;
        };
        if picked
            .get(&version)
            .is_none_or(|(known, ..)| build > *known)
        {
            picked.insert(version, (build, release, asset));
        }
    }
    picked
}

/// `llvmorg-18.1.8` → 18.1.8; `None` for release candidates and other tags.
fn parse_tag(tag: &str) -> Option<V> {
    tag.strip_prefix("llvmorg-")?.parse().ok()
}

/// The x86_64 Linux `.tar.xz` to install `version` from, by preference: the `LLVM-*-Linux-X64`
/// build, then the Ubuntu build with the lowest Ubuntu version, then RHEL, then SLES. Assets
/// whose name carries another version are ignored.
fn pick_asset(version: V, assets: &[Asset]) -> Option<&Asset> {
    assets
        .iter()
        .filter_map(|asset| Some((asset_rank(version, &asset.name)?, asset)))
        .min_by_key(|(rank, _)| *rank)
        .map(|(_, asset)| asset)
}

fn asset_rank(version: V, name: &str) -> Option<(u32, u32)> {
    if name == format!("LLVM-{version}-Linux-X64.tar.xz") {
        return Some((0, 0));
    }
    let platform = name
        .strip_prefix(&format!("clang+llvm-{version}-x86_64-"))?
        .strip_suffix(".tar.xz")?;
    if !platform.contains("linux") {
        return None;
    }
    if let Some((_, ubuntu)) = platform.split_once("ubuntu-") {
        let mut numbers = ubuntu.split('.').map(|n| n.parse::<u32>().unwrap_or(99));
        let major = numbers.next().unwrap_or(99);
        let minor = numbers.next().unwrap_or(99);
        return Some((1, major * 100 + minor));
    }
    if platform.contains("rhel") {
        return Some((2, 0));
    }
    if platform.contains("sles") {
        return Some((3, 0));
    }
    Some((4, 0))
}

/// The versions that go into the catalog, out of those with an asset.
fn wanted_versions(
    available: impl Iterator<Item = V> + Clone,
    add: &[V],
    known: impl Iterator<Item = V>,
) -> Vec<V> {
    let newest_of_major = |major: u32| available.clone().filter(|v| v.0 == major).max();
    let mut wanted: Vec<V> = available.clone().filter(|v| *v >= ALL_FROM).collect();
    wanted.extend((OLDEST_MAJOR..ALL_FROM.0).filter_map(newest_of_major));
    wanted.extend(add);
    wanted.extend(known);
    wanted.sort();
    wanted.dedup();
    wanted
}

struct Http {
    agent: ureq::Agent,
    token: Option<String>,
}

impl Http {
    fn new() -> Self {
        let config = ureq::Agent::config_builder()
            .user_agent("cxvm-xtask")
            .timeout_connect(Some(std::time::Duration::from_secs(30)))
            .build();
        Self {
            agent: config.into(),
            token: std::env::var("GITHUB_TOKEN").ok().filter(|t| !t.is_empty()),
        }
    }

    fn api_get(&self, url: &str) -> Result<ureq::http::Response<ureq::Body>> {
        let mut request = self
            .agent
            .get(url)
            .header("Accept", "application/vnd.github+json")
            .header("X-GitHub-Api-Version", "2022-11-28");
        if let Some(token) = &self.token {
            request = request.header("Authorization", format!("Bearer {token}"));
        }
        request.call().map_err(|e| format!("GET {url}: {e}"))
    }

    /// Every release of the repository whose releases API is `api`.
    fn releases(&self, api: &str) -> Result<Vec<Release>> {
        let mut releases = Vec::new();
        for page in 1.. {
            let url = format!("{api}?per_page=100&page={page}");
            let batch: Vec<Release> = self
                .api_get(&url)?
                .body_mut()
                .with_config()
                .limit(256 << 20)
                .read_json()
                .map_err(|e| format!("GET {url}: {e}"))?;
            if batch.is_empty() {
                break;
            }
            releases.extend(batch);
        }
        eprintln!("{} releases at {api}", releases.len());
        Ok(releases)
    }

    fn get_text(&self, url: &str) -> Result<String> {
        self.agent
            .get(url)
            .call()
            .map_err(|e| format!("GET {url}: {e}"))?
            .body_mut()
            .with_config()
            .limit(16 << 20)
            .read_to_string()
            .map_err(|e| format!("GET {url}: {e}"))
    }

    /// The sha256 upstream publishes for `asset`, and where it comes from. The GitHub digest
    /// and the attestation must agree when both exist.
    fn upstream_sha256(
        &self,
        release: &Release,
        asset: &Asset,
    ) -> Result<Option<(String, Source)>> {
        let sibling = |ext: &str| {
            let name = format!("{}{ext}", asset.name);
            release.assets.iter().find(move |a| a.name == name)
        };
        let digest = match &asset.digest {
            Some(digest) => Some(
                digest
                    .strip_prefix("sha256:")
                    .filter(|hex| is_sha256(hex))
                    .ok_or_else(|| format!("{}: unexpected digest `{digest}`", asset.name))?
                    .to_owned(),
            ),
            None => None,
        };
        let attested = match sibling(".jsonl") {
            Some(bundle) => Some(attested_sha256(
                &self.get_text(&bundle.browser_download_url)?,
                &asset.name,
            )?),
            None => None,
        };
        match (digest, attested) {
            (Some(digest), Some(attested)) if digest != attested => Err(format!(
                "{}: GitHub digest {digest} differs from the attested {attested}",
                asset.name
            )),
            (Some(digest), _) => Ok(Some((digest, Source::GithubDigest))),
            (None, Some(attested)) => Ok(Some((attested, Source::Attestation))),
            (None, None) => match sibling(".sha256") {
                Some(file) => {
                    let text = self.get_text(&file.browser_download_url)?;
                    let hex = sha256_file_entry(&text, &asset.name)
                        .ok_or_else(|| format!("{}: unexpected content `{text}`", file.name))?;
                    Ok(Some((hex, Source::UpstreamSha256)))
                }
                None => Ok(None),
            },
        }
    }

    /// The sha256 in the `<asset>.sha` file xPack publishes next to `asset`. The GitHub digest
    /// must agree when there is one.
    fn xpack_sha256(&self, release: &Release, asset: &Asset) -> Result<String> {
        let name = format!("{}.sha", asset.name);
        let file = release
            .assets
            .iter()
            .find(|a| a.name == name)
            .ok_or_else(|| format!("{}: the release has no {name}", release.tag_name))?;
        let text = self.get_text(&file.browser_download_url)?;
        let sha256 = sha256_file_entry(&text, &asset.name)
            .ok_or_else(|| format!("{name}: unexpected content `{text}`"))?;
        if let Some(digest) = &asset.digest
            && digest.strip_prefix("sha256:") != Some(&sha256)
        {
            return Err(format!(
                "{}: GitHub digest {digest} differs from {sha256} in {name}",
                asset.name
            ));
        }
        Ok(sha256)
    }

    /// Downloads `asset` without saving it and returns its sha256.
    fn hash(&self, asset: &Asset) -> Result<String> {
        let url = &asset.browser_download_url;
        eprintln!("hashing {} ({} MiB)", asset.name, asset.size >> 20);
        let response = self
            .agent
            .get(url)
            .call()
            .map_err(|e| format!("GET {url}: {e}"))?;
        let mut reader = response.into_body().into_reader();
        let mut hasher = Sha256::new();
        let mut buf = vec![0; 1 << 20];
        let (mut done, mut shown) = (0u64, 0u64);
        loop {
            let n = reader
                .read(&mut buf)
                .map_err(|e| format!("GET {url}: {e}"))?;
            if n == 0 {
                break;
            }
            hasher.update(&buf[..n]);
            done += n as u64;
            let percent = done * 100 / asset.size.max(1);
            if percent >= shown + 10 {
                shown = percent / 10 * 10;
                eprint!(" {shown}%");
                let _ = std::io::stderr().flush();
            }
        }
        eprintln!();
        if done != asset.size {
            return Err(format!(
                "{}: got {done} bytes, expected {}",
                asset.name, asset.size
            ));
        }
        Ok(hex(&hasher.finalize()))
    }
}

/// The sha256 of `asset` from a Sigstore bundle (`.jsonl`): the in-toto statement in its DSSE
/// payload lists the asset as a subject.
fn attested_sha256(bundle: &str, asset: &str) -> Result<String> {
    let fail = |why: &str| format!("{asset}.jsonl: {why}");
    for line in bundle.lines().filter(|l| !l.trim().is_empty()) {
        let value: serde_json::Value =
            serde_json::from_str(line).map_err(|e| fail(&e.to_string()))?;
        let payload = value["dsseEnvelope"]["payload"]
            .as_str()
            .ok_or_else(|| fail("no DSSE payload"))?;
        let statement = base64_decode(payload).ok_or_else(|| fail("payload is not base64"))?;
        let statement: serde_json::Value =
            serde_json::from_slice(&statement).map_err(|e| fail(&e.to_string()))?;
        let subjects = statement["subject"]
            .as_array()
            .ok_or_else(|| fail("no subject"))?;
        if let Some(hex) = subjects
            .iter()
            .filter(|s| s["name"] == asset)
            .find_map(|s| s["digest"]["sha256"].as_str())
        {
            return if is_sha256(hex) {
                Ok(hex.to_owned())
            } else {
                Err(fail("malformed sha256"))
            };
        }
    }
    Err(fail("the asset is not a subject"))
}

/// The hash for `asset` in `sha256sum` output (`<hex>  ./<name>`).
fn sha256_file_entry(text: &str, asset: &str) -> Option<String> {
    text.lines().find_map(|line| {
        let (hex, name) = line.split_once(char::is_whitespace)?;
        let name = name.trim().trim_start_matches('*').trim_start_matches("./");
        (name == asset && is_sha256(hex)).then(|| hex.to_owned())
    })
}

fn is_sha256(hex: &str) -> bool {
    hex.len() == 64 && hex.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// Standard base64 with padding; `None` on invalid input.
fn base64_decode(text: &str) -> Option<Vec<u8>> {
    let value = |c: u8| match c {
        b'A'..=b'Z' => Some(c - b'A'),
        b'a'..=b'z' => Some(c - b'a' + 26),
        b'0'..=b'9' => Some(c - b'0' + 52),
        b'+' => Some(62),
        b'/' => Some(63),
        _ => None,
    };
    let bytes = text.trim_end_matches('=').as_bytes();
    let mut out = Vec::with_capacity(bytes.len() * 3 / 4);
    let (mut acc, mut bits) = (0u32, 0);
    for &c in bytes {
        acc = (acc << 6) | u32::from(value(c)?);
        bits += 6;
        if bits >= 8 {
            bits -= 8;
            out.push((acc >> bits) as u8);
        }
    }
    Some(out)
}

