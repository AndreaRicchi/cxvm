    #[test]
    fn reads_the_attested_digest() {
        let statement = r#"{"subject":[{"name":"LLVM-19.1.7-Linux-X64.tar.xz","digest":{"sha256":"4a5ec53951a584ed36f80240f6fbf8fdd46b4cf6c7ee87cc2d5018dc37caf679"}}]}"#;
        let bundle = format!(
            r#"{{"dsseEnvelope":{{"payload":"{}"}}}}"#,
            base64_encode(statement.as_bytes())
        );
        assert_eq!(
            attested_sha256(&bundle, "LLVM-19.1.7-Linux-X64.tar.xz").unwrap(),
            "4a5ec53951a584ed36f80240f6fbf8fdd46b4cf6c7ee87cc2d5018dc37caf679"
        );
        assert!(attested_sha256(&bundle, "other.tar.xz").is_err());
    }

    #[test]
    fn reads_sha256sum_files() {
        let hex = "76d0bf002ede7a893f69d9ad2c4e101d15a8f4186fbfe24e74856c8449acd7c1";
        let text = format!("{hex}  ./clang+llvm-13.0.0-x86_64-linux-gnu-ubuntu-16.04.tar.xz\n");
        assert_eq!(
            sha256_file_entry(
                &text,
                "clang+llvm-13.0.0-x86_64-linux-gnu-ubuntu-16.04.tar.xz"
            ),
            Some(hex.to_owned())
        );
        assert_eq!(sha256_file_entry(&text, "other.tar.xz"), None);
    }

    #[test]
    fn base64_round_trips() {
        for input in ["", "f", "fo", "foo", "foob", "fooba", "foobar"] {
            assert_eq!(
                base64_decode(&base64_encode(input.as_bytes())).unwrap(),
                input.as_bytes()
            );
        }
        assert_eq!(base64_decode("Zm9vYmFy").unwrap(), b"foobar");
        assert_eq!(base64_decode("Zm9v!"), None);
    }

    fn base64_encode(bytes: &[u8]) -> String {
        const ALPHABET: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
        let mut out = String::new();
        for chunk in bytes.chunks(3) {
            let n = chunk.iter().fold(0u32, |acc, &b| (acc << 8) | u32::from(b))
                << (8 * (3 - chunk.len()));
            for i in 0..4 {
                if i <= chunk.len() {
                    out.push(ALPHABET[(n >> (18 - 6 * i) & 63) as usize] as char);
                } else {
                    out.push('=');
                }
            }
        }
        out
    }
