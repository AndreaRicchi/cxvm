    fn assets(names: &[&str]) -> Vec<Asset> {
        names
            .iter()
            .map(|name| Asset {
                name: (*name).to_owned(),
                size: 1,
                digest: None,
                browser_download_url: format!("https://example.invalid/{name}"),
            })
            .collect()
    }

    fn pick(version: &str, names: &[&str]) -> Option<String> {
        let assets = assets(names);
        pick_asset(version.parse().unwrap(), &assets).map(|a| a.name.clone())
    }

    #[test]
    fn picks_the_new_style_asset() {
        assert_eq!(
            pick(
                "22.1.8",
                &[
                    "LLVM-22.1.8-Linux-ARM64.tar.xz",
                    "LLVM-22.1.8-Linux-X64.tar.xz.jsonl",
                    "LLVM-22.1.8-Linux-X64.tar.xz.sig",
                    "LLVM-22.1.8-Linux-X64.tar.zst",
                    "LLVM-22.1.8-Linux-X64.tar.xz",
                    "clang+llvm-22.1.8-armv7a-linux-gnueabihf.tar.gz",
                ]
            )
            .as_deref(),
            Some("LLVM-22.1.8-Linux-X64.tar.xz")
        );
    }

    #[test]
    fn prefers_the_oldest_ubuntu_then_rhel_then_sles() {
        assert_eq!(
            pick(
                "13.0.0",
                &[
                    "clang+llvm-13.0.0-x86_64-linux-gnu-ubuntu-20.04.tar.xz",
                    "clang+llvm-13.0.0-x86_64-linux-gnu-ubuntu-16.04.tar.xz",
                    "clang+llvm-13.0.0-x86_64-linux-gnu-ubuntu-16.04.tar.xz.sha256",
                    "clang+llvm-13.0.0-aarch64-linux-gnu.tar.xz",
                ]
            )
            .as_deref(),
            Some("clang+llvm-13.0.0-x86_64-linux-gnu-ubuntu-16.04.tar.xz")
        );
        assert_eq!(
            pick(
                "15.0.2",
                &[
                    "clang+llvm-15.0.2-x86_64-unknown-linux-gnu-sles15.tar.xz",
                    "clang+llvm-15.0.2-x86_64-unknown-linux-gnu-rhel86.tar.xz",
                ]
            )
            .as_deref(),
            Some("clang+llvm-15.0.2-x86_64-unknown-linux-gnu-rhel86.tar.xz")
        );
        assert_eq!(
            pick(
                "12.0.0",
                &[
                    "clang+llvm-12.0.0-x86_64-linux-sles12.4.tar.xz",
                    "clang+llvm-12.0.0-x86_64-linux-gnu-ubuntu-20.04.tar.xz",
                ]
            )
            .as_deref(),
            Some("clang+llvm-12.0.0-x86_64-linux-gnu-ubuntu-20.04.tar.xz")
        );
    }

    #[test]
    fn ignores_assets_of_another_version_or_platform() {
        assert_eq!(
            pick(
                "11.0.0",
                &[
                    "clang+llvm-11.0.1-rc2-x86_64-linux-gnu-ubuntu-20.10.tar.xz",
                    "clang+llvm-11.0.0-x86_64-linux-sles12.4.tar.xz",
                ]
            )
            .as_deref(),
            Some("clang+llvm-11.0.0-x86_64-linux-sles12.4.tar.xz")
        );
        assert_eq!(
            pick(
                "18.1.8",
                &[
                    "clang+llvm-18.1.8-x86_64-pc-windows-msvc.tar.xz",
                    "clang+llvm-18.1.8-aarch64-linux-gnu.tar.xz",
                ]
            ),
            None
        );
        assert_eq!(
            pick(
                "1.0.1",
                &["clang+llvm-11.0.1-x86_64-linux-gnu-ubuntu-16.04.tar.xz"]
            ),
            None
        );
    }

    fn release(tag: &str, names: &[&str]) -> Release {
        Release {
            tag_name: tag.to_owned(),
            draft: false,
            prerelease: false,
            assets: assets(names),
        }
    }

    #[test]
    fn parses_xpack_tags() {
        assert_eq!(parse_xpack_tag("v13.3.0-2"), Some((V(13, 3, 0), 2)));
        assert_eq!(parse_xpack_tag("v8.5.0-1"), Some((V(8, 5, 0), 1)));
        assert_eq!(parse_xpack_tag("v13.3.0"), None);
        assert_eq!(parse_xpack_tag("v13.3-1"), None);
        assert_eq!(parse_xpack_tag("v13.3.0-1.1"), None);
        assert_eq!(parse_xpack_tag("13.3.0-1"), None);
    }

    #[test]
    fn picks_the_highest_xpack_build_with_a_linux_x64_archive() {
        let releases = [
            release(
                "v13.3.0-1",
                &[
                    "xpack-gcc-13.3.0-1-linux-x64.tar.gz",
                    "xpack-gcc-13.3.0-1-linux-x64.tar.gz.sha",
                ],
            ),
            release(
                "v13.3.0-2",
                &[
                    "xpack-gcc-13.3.0-2-linux-arm64.tar.gz",
                    "xpack-gcc-13.3.0-2-linux-x64.tar.gz.sha",
                    "xpack-gcc-13.3.0-2-linux-x64.tar.gz",
                    "xpack-gcc-13.3.0-2-win32-x64.zip",
                ],
            ),
            release("v14.1.0-2", &["xpack-gcc-14.1.0-2-darwin-x64.tar.gz"]),
            release("v14.1.0-1", &["xpack-gcc-14.1.0-1-linux-x64.tar.gz"]),
            Release {
                prerelease: true,
                ..release("v15.1.0-1", &["xpack-gcc-15.1.0-1-linux-x64.tar.gz"])
            },
        ];
        let picked: Vec<(String, u32, &str)> = pick_xpack_builds(&releases)
            .iter()
            .map(|(v, (build, _, asset))| (v.to_string(), *build, asset.name.as_str()))
            .collect();
        assert_eq!(
            picked,
            [
                (
                    "13.3.0".to_owned(),
                    2,
                    "xpack-gcc-13.3.0-2-linux-x64.tar.gz"
                ),
                (
                    "14.1.0".to_owned(),
                    1,
                    "xpack-gcc-14.1.0-1-linux-x64.tar.gz"
                ),
            ]
        );
    }

    #[test]
    fn catalog_arguments_select_the_kinds() {
        let parse = |args: &[&str]| {
            let args: Vec<String> = args.iter().map(|a| (*a).to_owned()).collect();
            parse_catalog_args(&args).map(|o| (o.clang, o.gcc))
        };
        assert_eq!(parse(&[]), Ok((true, true)));
        assert_eq!(parse(&["gcc"]), Ok((false, true)));
        assert_eq!(parse(&["clang", "--hash-missing"]), Ok((true, false)));
        assert_eq!(parse(&["--add", "17.0.2"]), Ok((true, true)));
        assert!(parse(&["gcc", "--hash-missing"]).is_err());
        assert!(parse(&["rust"]).is_err());
    }

